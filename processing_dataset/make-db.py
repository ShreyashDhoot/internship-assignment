import json
import sqlite3
from pathlib import Path

def setup_sqlite_db(db_path="artists.db"):
    """Creates a local SQLite database for native JSON queries."""
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS artist_documents (
            artist_id TEXT PRIMARY KEY,
            data TEXT CHECK(json_valid(data))
        )
    ''')
    conn.commit()
    return conn

def insert_into_db(conn, profile_data):
    """Inserts the JSON dictionary into SQLite."""
    cursor = conn.cursor()
    cursor.execute('''
        INSERT OR REPLACE INTO artist_documents (artist_id, data)
        VALUES (?, ?)
    ''', (profile_data.get("artist_id", "UNKNOWN"), json.dumps(profile_data)))
    conn.commit()

if __name__ == "__main__":
    dataset_path = Path(r"D:\INTERNSHIP-assigment\Data-set\artist_profiles")
    db_conn = setup_sqlite_db("artists.db")
    
    # Look ONLY for the JSON files generated by the first script
    json_files = list(dataset_path.rglob("profile.json"))
    
    if not json_files:
        print("No profile.json files found. Did you run extract_to_json.py first?")
    else:
        for json_file in json_files:
            # Load the JSON data
            with open(json_file, 'r', encoding='utf-8') as f:
                profile_data = json.load(f)
                
            # Insert into database
            insert_into_db(db_conn, profile_data)
            print(f"Inserted into DB: {profile_data.get('artist_id')} - {profile_data.get('name')}")

        db_conn.close()
        print(f"\nDatabase build complete. Inserted {len(json_files)} records into artists.db.")